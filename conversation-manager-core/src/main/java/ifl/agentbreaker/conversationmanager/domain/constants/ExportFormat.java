package ifl.agentbreaker.conversationmanager.domain.constants;

/** File representations supported by Conversation export. */
public enum ExportFormat
{
    /** Self-contained HTML document. */
    HTML,
    /** Machine-readable JSON representation. */
    JSON,
    /** Markdown document suitable for text workflows. */
    MARKDOWN,
    /** Plain-text representation without formatting. */
    TXT,
    ;
}
